"""Every sound and font in assets/ needs a row in THIRD_PARTY_NOTICES.md with a license we may ship.

A recorded Suno song nearly went into the app (docs/research/music-license.md). This check makes
that mistake fail the build instead of relying on someone remembering it.
"""
import re
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = ROOT / "THIRD_PARTY_NOTICES.md"
MEDIA = {".mp3", ".wav", ".m4a", ".ogg", ".aac", ".flac", ".opus", ".ttf", ".otf"}
ALLOWED = ("CC0 1.0", "SIL Open Font License 1.1", "Generated by")
BANNED_SOURCES = re.compile(r"(?i)suno|pixabay|youtube|recorded")


def notice_rows(text):
    """Return (where, license) for each table row that names a path."""
    rows = []
    for line in text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 3 or "`" not in cells[1]:
            continue  # header, separator or prose
        rows.append((cells[1], cells[2]))
    return rows


def covered(path, rows, root=ROOT):
    """A row covers a file when it names the file's folder and either the stem or no stems at all."""
    folder = f"{path.parent.relative_to(root).as_posix()}/"
    for where, license_ in rows:
        quoted = re.findall(r"`([^`]*)`", where)
        if folder not in quoted:
            continue
        stems = [q for q in quoted if "/" not in q]
        if not stems or path.stem in stems:
            return license_
    return None


def problems(root, rows):
    found = []
    for path in sorted((root / "assets").rglob("*")):
        if path.suffix.lower() not in MEDIA:
            continue
        license_ = covered(path, rows, root)
        name = path.relative_to(root).as_posix()
        if license_ is None:
            found.append(f"{name}: no row in THIRD_PARTY_NOTICES.md")
        elif not license_.startswith(ALLOWED):
            found.append(f"{name}: license we cannot ship ({license_})")
        elif BANNED_SOURCES.search(license_):
            found.append(f"{name}: recorded or terms-restricted source ({license_})")
        elif license_.startswith("Generated by"):
            script = re.search(r"`(tool/[^`]+)`", license_)
            if not script or not (root / script.group(1)).is_file():
                found.append(f"{name}: generating script is not in the repository ({license_})")
    return found


class AssetLicenses(unittest.TestCase):
    def test_every_bundled_sound_and_font_has_an_allowed_source(self):
        rows = notice_rows(NOTICES.read_text(encoding="utf-8"))
        self.assertEqual(problems(ROOT, rows), [])

    def check(self, files, rows):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            for name in files:
                (root / name).parent.mkdir(parents=True, exist_ok=True)
                (root / name).write_bytes(b"x")
            return problems(root, rows)

    def test_listed_cc0_and_generated_sounds_pass(self):
        rows = [
            ("`assets/sounds/basic/` (`tap_happy`)", "CC0 1.0, https://kenney.nl/assets/interface-sounds"),
            ("`assets/sounds/tones/`", "Generated by, `tool/make_tones.py`"),
        ]
        files = ["assets/sounds/basic/tap_happy.ogg", "assets/sounds/tones/c4.wav", "tool/make_tones.py"]
        self.assertEqual(self.check(files, rows), [])

    def test_an_unlisted_song_fails(self):
        found = self.check(["assets/music/sad.mp3"], [])
        self.assertEqual(len(found), 1)
        self.assertIn("assets/music/sad.mp3", found[0])

    def test_a_stem_missing_from_its_folder_row_fails(self):
        rows = [("`assets/sounds/basic/` (`tap_happy`)", "CC0 1.0, https://kenney.nl")]
        self.assertEqual(len(self.check(["assets/sounds/basic/tap_new.ogg"], rows)), 1)

    def test_recordings_and_unshippable_licenses_fail(self):
        cases = [
            ("CC0 1.0, recorded from suno.com", []),
            ("Pixabay Content License", []),
            ("Generated by, `tool/missing_script.py`", []),
        ]
        for license_, extra in cases:
            with self.subTest(license_):
                rows = [("`assets/music/`", license_)]
                self.assertEqual(len(self.check(["assets/music/song.mp3", *extra], rows)), 1)


if __name__ == "__main__":
    unittest.main()
