#!/usr/bin/env python3
"""Make the app icon shortcut icons from the mood faces and design/tokens.json.

  python3 tool/gen_shortcut_icons.py           write the files
  python3 tool/gen_shortcut_icons.py --check   only verify that the files are current (CI)

Android: android/app/src/main/res/drawable/shortcut_<mood>.xml, a vector drawable. The launcher
cuts the icon to a circle, so the face sits on a full circle in the light surface color and is
drawn in the light mood color.
iOS: ios/Runner/Assets.xcassets/shortcut_<mood>.imageset, an SVG of the face lines only. iOS draws
shortcut icons as a single color template, so the file has no color of its own.

The faces are the paths in assets/icons/mood_<mood>.svg and the colors are light.moodX and
light.surface, so a face or a color changed there reaches the shortcuts by running this again.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_tokens import ROOT, TokenError, load, opaque_rgb  # noqa: E402

MOODS = ("happy", "excited", "angry", "sad", "anxious")
ANDROID_DIR = Path("android/app/src/main/res/drawable")
IOS_DIR = Path("ios/Runner/Assets.xcassets")
FACE = ROOT / "assets" / "icons"
ELEMENT = re.compile(r"<(circle|path)\b([^>]*)/>")
ATTR = re.compile(r'([\w-]+)="([^"]*)"')


def icon_name(mood):
    return f"shortcut_{mood}"


def face_parts(mood):
    """The face as [(pathData, strokeWidth)], read from the face SVG."""
    svg = (FACE / f"mood_{mood}.svg").read_text(encoding="utf-8")
    base = float(re.search(r'stroke-width="([\d.]+)"', svg).group(1))
    parts = []
    for kind, attrs in ELEMENT.findall(svg):
        a = dict(ATTR.findall(attrs))
        if kind == "circle":
            cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
            data = f"M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0"
        else:
            data = a["d"]
        parts.append((data, a.get("stroke-width", f"{base:g}")))
    return parts


def android_xml(mood, tokens):
    color = opaque_rgb(tokens, "light", f"mood{mood.capitalize()}")
    ground = opaque_rgb(tokens, "light", "surface")
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tool/gen_shortcut_icons.py from the mood face and design/tokens.json. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="48dp"',
        '    android:height="48dp"',
        '    android:viewportWidth="24"',
        '    android:viewportHeight="24">',
        "    <path",
        f'        android:fillColor="#{ground}"',
        '        android:pathData="M12,0a12,12 0 1,0 0,24a12,12 0 1,0 0,-24" />',
    ]
    for data, width in face_parts(mood):
        lines += [
            "    <path",
            f'        android:pathData="{data}"',
            f'        android:strokeColor="#{color}"',
            f'        android:strokeWidth="{width}"',
            '        android:strokeLineCap="round"',
            '        android:strokeLineJoin="round" />',
        ]
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def ios_svg(mood):
    shapes = "".join(f'<path d="{d}" stroke-width="{w}"/>' for d, w in face_parts(mood))
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
        'stroke="#000000" stroke-linecap="round" stroke-linejoin="round">' + shapes + "</svg>\n"
    )


def ios_contents(mood):
    doc = {
        "images": [{"filename": f"{icon_name(mood)}.svg", "idiom": "universal"}],
        "info": {"author": "xcode", "version": 1},
        "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
    }
    return json.dumps(doc, indent=2) + "\n"


def outputs(tokens):
    """Every file to generate, as {repo-relative path: content}."""
    out = {}
    for mood in MOODS:
        name = icon_name(mood)
        out[ANDROID_DIR / f"{name}.xml"] = android_xml(mood, tokens)
        out[IOS_DIR / f"{name}.imageset" / f"{name}.svg"] = ios_svg(mood)
        out[IOS_DIR / f"{name}.imageset" / "Contents.json"] = ios_contents(mood)
    return out


def stale(outs, root=ROOT):
    return [
        rel
        for rel, text in outs.items()
        if not (root / rel).is_file() or (root / rel).read_text(encoding="utf-8") != text
    ]


def main(argv):
    try:
        outs = outputs(load())
    except (TokenError, KeyError, OSError) as e:
        print(f"shortcut icons error: {e}", file=sys.stderr)
        return 1
    old = stale(outs)
    if argv == ["--check"]:
        if old:
            print("shortcut icons are out of date: " + ", ".join(str(p) for p in old)
                  + ". Run python3 tool/gen_shortcut_icons.py and commit the result.", file=sys.stderr)
            return 1
        return 0
    for rel in old:
        (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / rel).write_text(outs[rel], encoding="utf-8")
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
